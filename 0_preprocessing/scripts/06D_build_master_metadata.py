# NOMBRE: 06D_build_master_metadata.py
# DESCRIPCIÓN: Combina los metadatos enriquecidos de cada estudio 
#              (*_metadata_q2_format_enriched.tsv) en una sola 
#              tabla maestra para análisis downstream en R.
# USO: python 0_preprocessing/scripts/06D_build_master_metadata.py
# ============================================================

import glob
import os
import pandas as pd

METADATA_DIR = "data/pre_processed/metadata"
OUTPUT_DIR = "data/pre_processed/unified"

os.makedirs(OUTPUT_DIR, exist_ok=True)

# Find all enriched metadata files generated by step 03
all_files = glob.glob(os.path.join(METADATA_DIR, "*_metadata_q2_format_enriched.tsv"))

if not all_files:
    print(f"❌ ERROR: No se encontraron archivos de metadatos enriquecidos en {METADATA_DIR}")
    exit(1)

dfs = []
type_row = None

for filepath in sorted(all_files):
    study_id = os.path.basename(filepath).split("_metadata_q2")[0]
    print(f"📋 Leyendo metadatos para {study_id}: {os.path.basename(filepath)}")
    
    # Check if the file contains the QIIME 2 #q2:types header row on the second line
    with open(filepath, 'r') as file:
        file.readline() # Read column names header
        second_line = file.readline().strip().split('\t')
    
    has_q2_types = second_line[0] == "#q2:types" or any(t in ["numeric", "categorical"] for t in second_line)
    
    if has_q2_types:
        # Read normally, skipping the second row (type row) for concatenation
        df = pd.read_csv(filepath, sep="\t", skiprows=[1])
        if type_row is None:
            # Capture the type row mapping from the first valid file encountered
            type_df = pd.read_csv(filepath, sep="\t", nrows=1)
            type_row = type_df.iloc[0].to_dict()
    else:
        df = pd.read_csv(filepath, sep="\t")
        
    dfs.append(df)

# Concatenate all study metadata tables vertically
master_df = pd.concat(dfs, ignore_index=True)

# Re-insert the QIIME 2 #q2:types header row cleanly at the top if captured
if type_row:
    types_df = pd.DataFrame([type_row])
    master_df = pd.concat([types_df, master_df], ignore_index=True)

# Save master metadata table for R / Phyloseq
output_path = os.path.join(OUTPUT_DIR, "master_metadata_unified.tsv")
master_df.to_csv(output_path, sep="\t", index=False)
print(f"🎉 Master metadata creada exitosamente en: {output_path}")

